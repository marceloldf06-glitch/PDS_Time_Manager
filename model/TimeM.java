package model;

public class TimeM {
	String Nome, Data;
	int HRInicio, HRFim, Tag, IdHorarios;

	public String getNome() {
		return Nome;
	}

	public void setNome(String nome) {
		Nome = nome;
	}

	public String getData() {
		return Data;
	}

	public void setData(String data) {
		Data = data;
	}

	public int getHRInicio() {
		return HRInicio;
	}

	public void setHRInicio(int hrInicio) {
		HRInicio = hrInicio;
	}

	public int getHRFim() {
		return HRFim;
	}

	public void setHRFim(int hRFim) {
		HRFim = hRFim;
	}

	public int getTag() {
		return Tag;
	}

	public void setTag(int tag) {
		Tag = tag;
	}

}
